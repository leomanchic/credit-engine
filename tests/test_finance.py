"""Section 17 constants are copied from the independently checked specification.

Expected values are not generated by evaluate or by functions under test.
The separate audit script records a direct 60-digit formula calculation.
"""

from decimal import Decimal, Inexact, ROUND_DOWN, localcontext

import pytest

from credit_engine.collateral import market_recovery
from credit_engine.finance import (
    annuity,
    cash_limit,
    display_dscr,
    display_schedule,
    dscr,
    floor_money,
    floor_step,
    meets_dscr,
    round_money,
)

D = Decimal


@pytest.mark.parametrize(
    "amount,months,cashflow,monthly,last,total,ratio",
    [
        ("2000000", 24, "200000", "105742.19", "105742.30", "2537812.67", "1.372286"),
        ("900000", 24, "200000", "47583.99", "47583.93", "1142015.70", "2.283522"),
        ("400000", 24, "80000", "21148.44", "21148.41", "507562.53", "1.308292"),
        ("1760000", 24, "200000", "93053.13", "93053.16", "2233275.15", "1.503159"),
        ("2000000", 36, "200000", "78465.71", "78465.54", "2824765.39", "1.688252"),
        ("2000000", 12, "200000", "189119.19", "189119.23", "2269430.32", "0.872908"),
    ],
)
def test_section17_schedule(amount, months, cashflow, monthly, last, total, ratio):
    actual = display_schedule(D(amount), months, D("0.24"), D("2000000"))
    assert actual["monthly_payment"] == D(monthly)
    assert actual["last_payment"] == D(last)
    assert actual["total_payment"] == D(total)
    assert actual["monthly_payment"] * (months - 1) + actual["last_payment"] == D(total)
    assert actual["interest"] == D(total) - D(amount)
    assert actual["funding_gap"] == max(D("0"), D("2000000") - D(amount))
    payment = annuity(D(amount), months, D("0.24"))
    assert display_dscr(dscr(D(cashflow), D("40000"), payment)) == D(ratio)


@pytest.mark.parametrize(
    "cashflow,threshold,limit,step_amount",
    [
        ("80000", "1.30", "407376.859142782560197579556084811868104094550354169273109488", "400000"),
        ("200000", "1.30", "2153277.68404042210390149193930543415997878548044346615786443", "2150000"),
        ("200000", "1.50", "1765299.72295205776085617807636751809511774305153473351680777", "1760000"),
    ],
)
def test_section17_cash_limits(cashflow, threshold, limit, step_amount):
    actual = cash_limit(D(cashflow), D("40000"), 24, D("0.24"), D(threshold))
    assert abs(actual - D(limit)) < D("1e-24")
    assert floor_step(actual, D("10000")) == D(step_amount)


def test_zero_rate_has_exact_linear_payment_and_capacity():
    assert annuity(D("120000"), 12, D("0")) == D("10000")
    assert cash_limit(D("65000"), D("10000"), 12, D("0"), D("1.30")) == D("480000")
    assert display_schedule(D("100.00"), 3, D("0"), D("100.00")) == {
        "monthly_payment": D("33.33"),
        "last_payment": D("33.34"),
        "total_payment": D("100.00"),
        "interest": D("0.00"),
        "funding_gap": D("0.00"),
    }


@pytest.mark.parametrize("threshold", [D("1.30"), D("1.50")])
def test_exact_dscr_boundaries_use_unrounded_inequality(threshold):
    # A zero-rate loan yields P=10000 exactly, so the boundary is independent.
    cashflow = threshold * D("50000")
    assert meets_dscr(cashflow, D("40000"), D("10000"), threshold)
    assert meets_dscr(cashflow + D("0.000001"), D("40000"), D("10000"), threshold)
    assert not meets_dscr(cashflow - D("0.000001"), D("40000"), D("10000"), threshold)
    below = dscr(cashflow - D("0.000001"), D("40000"), D("10000"))
    assert display_dscr(below) == threshold


@pytest.mark.parametrize("cashflow", [D("0"), D("-1"), D("-200000")])
def test_nonpositive_cashflow_has_zero_capacity(cashflow):
    assert cash_limit(cashflow, D("0"), 24, D("0.24"), D("1.30")) == D("0")
    assert dscr(cashflow, D("0"), D("100")) <= 0


def test_money_rounding_and_alternative_step():
    assert round_money(D("1.005")) == D("1.01")
    assert round_money(D("-1.005")) == D("-1.01")
    assert floor_money(D("1.009")) == D("1.00")
    assert floor_step(D("1999999.99"), D("10000")) == D("1990000")


def test_lower_debt_cannot_reduce_cash_limit():
    for cashflow in (D("75000"), D("112345.67"), D("240000")):
        for months in (6, 12, 18, 24, 36):
            assert cash_limit(cashflow, D("20000"), months, D("0.24"), D("1.30")) >= cash_limit(
                cashflow, D("40000"), months, D("0.24"), D("1.30")
            )


def test_all_financial_functions_are_independent_of_ambient_decimal_context():
    expected = display_schedule(D("2000000"), 24, D("0.24"), D("2000000"))
    expected_limit = cash_limit(D("200000"), D("40000"), 24, D("0.24"), D("1.30"))
    with localcontext() as ambient:
        ambient.prec = 3
        ambient.rounding = ROUND_DOWN
        ambient.traps[Inexact] = True
        assert display_schedule(D("2000000"), 24, D("0.24"), D("2000000")) == expected
        assert cash_limit(D("200000"), D("40000"), 24, D("0.24"), D("1.30")) == expected_limit
        assert display_dscr(dscr(D("200000"), D("40000"), annuity(D("2000000"), 24, D("0.24")))) == D("1.372286")
        assert floor_step(expected_limit, D("10000")) == D("2150000")
        assert ambient.prec == 3
        assert ambient.traps[Inexact] is True


@pytest.mark.parametrize("bad", [1.25, D("NaN"), D("Infinity")])
def test_pure_functions_do_not_accept_floats_or_nonfinite_values(bad):
    with pytest.raises(ValueError):
        annuity(bad, 12, D("0.24"))


